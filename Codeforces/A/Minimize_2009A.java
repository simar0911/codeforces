package Codeforces.A;
import java.util.*;
public class Minimize_2009A {
       public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);

        int t = sc.nextInt();

        for (int i = 0; i < t; i++) {
            int a = sc.nextInt();
            int b = sc.nextInt();

            System.out.println(b - a);
        }
    }
}
